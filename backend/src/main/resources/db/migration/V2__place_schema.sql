-- SnapHere V2 — 장소 기준정보와 장소
-- 요구사항: PLC-001, PLC-002, PLC-003, PLC-007, PLC-020, PLC-022, PLC-023
-- 설계: docs/12-db-schema.dbml · docs/04-data-design.md
